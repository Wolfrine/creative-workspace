import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const evidence = process.env.NOVELIAA_EVIDENCE_DIR ?? '.local/sync-browser';
for (const width of [1440, 390, 320]) test(`quiet sync icon, exact idle timer, recovery and details at ${width}px`, async ({ page }) => {
  await mkdir(evidence, { recursive: true });
  await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 });
  await page.clock.install();
  await page.goto('/?local=1&notebook=idle-' + width + '-' + Date.now());
  await page.waitForFunction(() => (window as any).__NOVELIAA_TEST__?.getSnapshot().ready);
  await page.getByRole('button', { name: 'Begin writing', exact: true }).click();
  await page.getByRole('textbox', { name: 'Writing title', exact: true }).fill('The room above the tide');
  const canvas = page.getByRole('textbox', { name: 'Writing canvas', exact: true });
  await canvas.fill('I kept the window open.\n\nThe sea had something left to say.');
  await page.clock.pauseAt(new Date(Date.now() + 1000));
  await canvas.press('End'); await canvas.pressSequentially(' हिंदी é 🙂');
  await page.clock.runFor(9_999);
  await expect(page.getByRole('button', { name: 'Changes waiting for device save', exact: true })).toBeVisible();
  const revisionCount = await page.evaluate(() => (window as any).__NOVELIAA_TEST__.getSnapshot().revisions.length);
  await page.clock.runFor(1);
  await expect(page.getByRole('button', { name: 'Saved on this device', exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as any).__NOVELIAA_TEST__.getSnapshot().revisions.length)).toBe(revisionCount);
  const icon = page.locator('.save-status');
  await expect(icon).toHaveText(''); await expect(icon).not.toHaveAttribute('role', 'status');
  expect(await icon.locator('svg').evaluate(element => getComputedStyle(element).animationName)).toBe('none');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `${evidence}/quiet-writing-${width}.png`, fullPage: true });
  await icon.click(); await expect(page.getByRole('dialog', { name: 'Writing sync', exact: true })).toBeVisible();
  await expect(page.getByText('Writing saves on this device after 10 seconds without an edit. Cloud saving starts after 60 seconds without an edit.', { exact: true })).toBeVisible();
  await page.screenshot({ path: `${evidence}/sync-details-${width}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Close writing sync', exact: true }).click();
  await page.clock.resume();
  await page.reload(); await expect(canvas).toContainText('The sea had something left to say.');
  await expect(canvas).toContainText('हिंदी');
});
