import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const url = 'https://noveliaa.web.app';
const directory = 'docs/evidence/phase1/spark-hosted';
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.message));
const response = await page.goto(url, { waitUntil: 'networkidle' });
assert.equal(response.status(), 200);
await page.getByRole('button', { name: /Sign in with Google/ }).waitFor();
assert.equal(await page.getByRole('textbox', { name: 'Writing canvas', exact: true }).count(), 0);
await page.evaluate(() => document.fonts.ready);
const desktop = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
assert.equal(desktop.violations.length, 0);
await page.screenshot({ path: directory + '/desktop.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
const mobile = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
assert.equal(mobile.violations.length, 0);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
await page.screenshot({ path: directory + '/mobile.png', fullPage: true });
await page.setViewportSize({ width: 320, height: 640 });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
await page.screenshot({ path: directory + '/mobile-320.png', fullPage: true });
await page.evaluate(() => navigator.serviceWorker.ready);
await page.reload({ waitUntil: 'networkidle' });
await page.waitForFunction(() => navigator.serviceWorker.controller);
await context.setOffline(true); await page.reload({ waitUntil: 'domcontentloaded' });
await page.getByRole('button', { name: /Sign in with Google/ }).waitFor();
await context.setOffline(false);
const config = await (await page.request.get(url + '/__/firebase/init.json')).json();
assert.equal(config.projectId, 'noveliaa');
assert.equal(config.appId, '1:278082781314:web:9a4b7acef07fa8e4dfb49b');
assert.deepEqual(errors, []);
const result = { checkedAt: new Date().toISOString(), url, projectId: config.projectId, appId: config.appId, desktop: '1440x1000', mobile: ['390x844', '320x640'], desktopAxe: desktop.violations, mobileAxe: mobile.violations, horizontalOverflow: false, pageErrors: errors, offlinePublicShell: 'cold reload passed with cached sign-in gate', authenticatedOwnerAcceptance: 'Human Google sign-in required; no production bypass or manuscript seed' };
await writeFile(directory + '/visual-check.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
await browser.close();
